/**
 * Get static translation for a given text and language
 */
export function getStaticTranslation(text: string, targetLanguage: string): string | undefined {
  // Normalize language code
  const normalized = targetLanguage.toLowerCase().split('-')[0];
  
  // Return English text for English
  if (normalized === 'en') {
    return text;
  }

  // Look up in static translations
  const languageDict = STATIC_TRANSLATIONS[normalized];
  const supplemental = SUPPLEMENTAL_STATIC_TRANSLATIONS[normalized];
  return languageDict?.[text] ?? supplemental?.[text];
}

/**
 * Check if a translation dictionary exists for a language
 */
export function hasStaticDictionary(language: string): boolean {
  const normalized = language.toLowerCase().split('-')[0];
  return normalized === 'en' || !!STATIC_TRANSLATIONS[normalized];
}

/**
 * Get all static translations for a language
 */
export function getStaticDictionary(language: string): Record<string, string> {
  const normalized = language.toLowerCase().split('-')[0];
  if (normalized === 'en') {
    return {};
  }
  return STATIC_TRANSLATIONS[normalized] ?? {};
}
